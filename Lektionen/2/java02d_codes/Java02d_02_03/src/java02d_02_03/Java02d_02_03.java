package java02d_02_03;

public class Java02d_02_03 { 
	public static void main(String[] args) { 
		System.out.print("Textausgabe in Java,\nmit Zeilenumbruch\n"); 
		System.out.print("Textausgabe\nin\nJava,\n"); 
		System.out.print("mit\nZeilenumbruch\n\n"); 
		System.out.println("Textausgabe\nin Java,\n"); 
		System.out.println("\nmit Zeilenumbruch"); 
	} 
} 