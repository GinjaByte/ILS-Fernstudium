package java03d_04_02;

public class Java03d_04_02 {
	//die erste Methode ausgabe1()
	static void ausgabe1() {
		System.out.println("Java macht Spaß. :)");
	}

	//die zweite Methode ausgabe2()
	static void ausgabe2() {
		System.out.println("Aber nicht immer. :(");
	}

	public static void main(String[] args) {
		//der Aufruf der ersten Methode
		ausgabe1();

		//der Aufruf der zweiten Methode
		ausgabe2();

		System.out.println("Das war es.");
	}
}
