package java02d_03_03;

public class Java02d_03_03 {
	public static void main(String[] args) {
		//Vereinbarung einer Variablen zahl für ganze Zahlen
		int zahl;
		//1. Zuweisung
		zahl = 10;
		//1. Ausgabe
		System.out.printf("zahl hat den Wert %d\n",zahl);
		//2. Ausgabe
		System.out.printf("zahl hat den Wert %d\n",zahl);
		//2. Zuweisung
		zahl = 22;
		System.out.printf("zahl hat jetzt den Wert %d\n",zahl);
	}
}
